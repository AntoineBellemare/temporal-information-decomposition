def plot_global_matrix(results, channel, save_path=None):
    fig, axes = plt.subplots(2, 2, figsize=(12, 10))
    lag_vals, lag_idx = lag_index(results)
    n_lags = len(lag_vals)
    tick_labels = lag_tick_labels(lag_vals)
    comps  = ['redundancy', 'synergy', 'unique_0', 'unique_1']
    titles = ['Redundancy', 'Synergy', 'Unique (lag 1)', 'Unique (lag 2)']
    cmaps  = ['Greens', 'Reds', 'Blues', 'Purples']
    for ax, comp, title, cmap in zip(axes.flat, comps, titles, cmaps):
        mat = np.full((n_lags, n_lags), np.nan)
        for _, r in results.iterrows():
            mat[lag_idx[r['lag1_min']], lag_idx[r['lag2_min']]] = r[comp]
        sns.heatmap(mat, ax=ax, cmap=cmap, mask=np.isnan(mat),
                    xticklabels=tick_labels, yticklabels=tick_labels,
                    cbar_kws={'label': 'bits'})
        ax.set_title(title, fontweight='bold')
        ax.set_xlabel('Lag 2 (min)')
        ax.set_ylabel('Lag 1 (min)')
    plt.suptitle(f'Global Temporal PID — minute-scale lags\n'
                 f'({channel}, {DURATION_HOURS}h, {N_BINS} bins)',
                 fontsize=14, fontweight='bold')
    plt.tight_layout()
    if save_path:
        plt.savefig(save_path, dpi=150, bbox_inches='tight')
        plt.close()


def plot_combined_timeseries(tr, tr_ar1, stage_labels, channel, save_path=None):
    windows = sorted(tr['time_min'].unique())
    w_arr = np.array(windows)
    agg_act = tr.groupby('time_min').agg(
        redundancy=('redundancy', 'mean'), synergy=('synergy', 'mean'),
        unique_0=('unique_0', 'mean'), unique_1=('unique_1', 'mean'),
    ).reset_index()
    tr_u = tr.copy()
    tr_u['unique_total'] = tr_u['unique_0'] + tr_u['unique_1']
    pctiles = {}
    for col in ['redundancy', 'synergy', 'unique_total']:
        p10, p25, p75, p90 = [], [], [], []
        for ww in windows:
            vals = tr_u.loc[tr_u['time_min'] == ww, col].dropna()
            p10.append(np.percentile(vals, 10)); p25.append(np.percentile(vals, 25))
            p75.append(np.percentile(vals, 75)); p90.append(np.percentile(vals, 90))
        pctiles[col] = (np.array(p10), np.array(p25), np.array(p75), np.array(p90))
    agg_ar1 = tr_ar1.groupby('time_min').agg(
        redundancy=('redundancy', 'mean'), synergy=('synergy', 'mean'),
        unique_0=('unique_0', 'mean'), unique_1=('unique_1', 'mean'),
    ).reset_index()
    mrg = agg_act.merge(agg_ar1, on='time_min', suffixes=('', '_ar1'))
    t = mrg['time_min'].values
    fig, axes = plt.subplots(4, 1, figsize=(16, 12),
                             gridspec_kw={'height_ratios': [0.7, 1, 1, 1]}, sharex=True)
    stage_num = {'Wake': 0, 'REM': -0.5, 'N1': -1, 'N2': -2, 'N3': -3, '?': 0.5}
    hyp_y = [stage_num.get(s, 0.5) for s in stage_labels]
    hyp_x = np.arange(len(stage_labels)) * MIN_PER_WINDOW
    axes[0].step(hyp_x, hyp_y, where='post', color='black', lw=1.5)
    axes[0].set_yticks([0, -0.5, -1, -2, -3])
    axes[0].set_yticklabels(['Wake', 'REM', 'N1', 'N2', 'N3'])
    axes[0].set_ylabel('Stage'); axes[0].set_title('Hypnogram', fontweight='bold')
    add_stage_background(axes[0], stage_labels)
    axes[0].legend(handles=stage_legend_handles(), loc='upper right', ncol=5, fontsize=8, framealpha=0.8)
    axes[0].grid(axis='x', alpha=0.3)
    panels = [('redundancy', 'green', 'Redundancy'), ('synergy', 'red', 'Synergy')]
    for ax, (col, color, label) in zip(axes[1:3], panels):
        actual_v = mrg[col].values; ar1_v = mrg[f'{col}_ar1'].values
        p10, p25, p75, p90 = pctiles[col]
        ax.fill_between(w_arr, p10, p90, alpha=0.08, color=color, label='10–90 %ile')
        ax.fill_between(w_arr, p25, p75, alpha=0.18, color=color, label='25–75 %ile')
        ax.fill_between(t, ar1_v, alpha=0.3, color='gray', label='AR(1) baseline')
        ax.plot(t, actual_v, color=color, lw=1.5, label='Mean', zorder=3)
        ax.plot(t, actual_v - ar1_v, color=color, lw=1, ls='--', alpha=0.6, label='Excess', zorder=2)
        ax.axhline(0, color='black', lw=0.5, alpha=0.3)
        ax.set_ylabel(f'{label}\n(bits)'); ax.legend(loc='upper right', fontsize=7, ncol=2)
        add_stage_background(ax, stage_labels); ax.grid(axis='x', alpha=0.3)
    act_uniq = mrg['unique_0'].values + mrg['unique_1'].values
    ar1_uniq = mrg['unique_0_ar1'].values + mrg['unique_1_ar1'].values
    p10, p25, p75, p90 = pctiles['unique_total']
    axes[3].fill_between(w_arr, p10, p90, alpha=0.08, color='blue', label='10–90 %ile')
    axes[3].fill_between(w_arr, p25, p75, alpha=0.18, color='blue', label='25–75 %ile')
    axes[3].fill_between(t, ar1_uniq, alpha=0.3, color='gray', label='AR(1) baseline')
    axes[3].plot(t, act_uniq, color='blue', lw=1.5, label='Mean', zorder=3)
    axes[3].plot(t, act_uniq - ar1_uniq, color='blue', lw=1, ls='--', alpha=0.6, label='Excess', zorder=2)
    axes[3].axhline(0, color='black', lw=0.5, alpha=0.3)
    axes[3].set_ylabel('Total Unique\n(bits)'); axes[3].legend(loc='upper right', fontsize=7, ncol=2)
    add_stage_background(axes[3], stage_labels); axes[3].grid(axis='x', alpha=0.3)
    axes[-1].set_xlabel('Time (min)')
    plt.suptitle(f'Temporal PID evolution during sleep\n'
                 f'({channel}, mean + spread across lag pairs, AR(1) baseline)',
                 fontsize=14, fontweight='bold')
    plt.tight_layout()
    if save_path:
        plt.savefig(save_path, dpi=150, bbox_inches='tight'); plt.close()


