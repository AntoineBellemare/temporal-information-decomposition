def _discover_all_params():
    """Return list of (params_dict, chash) for every params JSON with matching data."""
    if not RESULTS_DIR.exists():
        return []
    results = []
    for pf in sorted(RESULTS_DIR.glob("params_*.json"),
                     key=lambda p: p.stat().st_mtime):
        chash = pf.stem.split("_", 1)[1]
        with open(pf) as f:
            params = json.load(f)
        # check if any channel has data for this hash
        has_data = False
        bands = params.get("BANDS", None)
        for d in RESULTS_DIR.iterdir():
            if not d.is_dir():
                continue
            if (d / f"timeresolved_pid_filtered_{chash}.csv").exists():
                has_data = True
                break
            if bands:
                for b in bands:
                    if (d / b / f"timeresolved_pid_filtered_{chash}.csv").exists():
                        has_data = True
                        break
            if has_data:
                break
        if has_data:
            results.append((params, chash))
    return results


