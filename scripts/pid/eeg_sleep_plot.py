def plot_effect_sizes(tr, channel, save_path=None):
    tr_common = common_lag_range(tr)
    agg = tr_common.groupby(['time_min', 'stage']).agg(
        redundancy=('redundancy', 'mean'), synergy=('synergy', 'mean'),
        unique_0=('unique_0', 'mean'), unique_1=('unique_1', 'mean'),
    ).reset_index()
    agg['unique_total'] = agg['unique_0'] + agg['unique_1']
    agg['ratio'] = agg['synergy'] / agg['redundancy'].replace(0, np.nan)
    agg = agg[agg['stage'].isin(STAGE_ORDER)]
    present = [s for s in STAGE_ORDER if s in agg['stage'].unique()]
    fig, axes = plt.subplots(1, 4, figsize=(18, 4))
    for ax, metric, label in zip(axes, ['redundancy', 'synergy', 'unique_total', 'ratio'],
                                  ['Redundancy', 'Synergy', 'Total Unique', 'S/R Ratio']):
        n = len(present); d_mat = np.full((n, n), np.nan); p_mat = np.full((n, n), np.nan)
        for i, s1 in enumerate(present):
            for j, s2 in enumerate(present):
                if i >= j: continue
                v1 = agg.loc[agg['stage'] == s1, metric].dropna().values
                v2 = agg.loc[agg['stage'] == s2, metric].dropna().values
                if len(v1) < 3 or len(v2) < 3: continue
                pooled_std = np.sqrt(((len(v1)-1)*np.var(v1, ddof=1) + (len(v2)-1)*np.var(v2, ddof=1)) / (len(v1) + len(v2) - 2))
                if pooled_std > 0:
                    d_mat[i, j] = (np.mean(v1) - np.mean(v2)) / pooled_std; d_mat[j, i] = -d_mat[i, j]
                _, p_val = mannwhitneyu(v1, v2, alternative='two-sided'); p_mat[i, j] = p_val; p_mat[j, i] = p_val
        upper_p, upper_idx = [], []
        for i in range(n):
            for j in range(i + 1, n):
                if not np.isnan(p_mat[i, j]): upper_p.append(p_mat[i, j]); upper_idx.append((i, j))
        p_mat_fdr = np.full((n, n), np.nan)
        if upper_p:
            adj_p = benjamini_hochberg(upper_p)
            for (i, j), ap in zip(upper_idx, adj_p): p_mat_fdr[i, j] = ap; p_mat_fdr[j, i] = ap
        vmax = np.nanmax(np.abs(d_mat)) if not np.all(np.isnan(d_mat)) else 1
        sns.heatmap(d_mat, ax=ax, cmap='RdBu_r', center=0, vmin=-vmax, vmax=vmax,
                    xticklabels=present, yticklabels=present, annot=True, fmt='.2f',
                    annot_kws={'fontsize': 8}, cbar_kws={'label': "Cohen's d", 'shrink': 0.8}, mask=np.isnan(d_mat))
        for i in range(n):
            for j in range(n):
                if not np.isnan(p_mat_fdr[i, j]) and p_mat_fdr[i, j] < 0.05:
                    ax.text(j + 0.5, i + 0.8, '*', ha='center', va='center', fontsize=10, fontweight='bold')
        ax.set_title(label, fontweight='bold')
    plt.suptitle(f"Effect sizes (Cohen's d) between sleep stages ({channel})\n(* = FDR p < 0.05)",
                 fontsize=13, fontweight='bold')
    plt.tight_layout()
    if save_path:
        plt.savefig(save_path, dpi=150, bbox_inches='tight'); plt.close()


def plot_block_permutation(global_results, null_vals, channel, save_path=None):
    lag_vals, l_idx = lag_index(global_results)
    n_lags = len(lag_vals)
    tick_labels = lag_tick_labels(lag_vals)
    # rebuild lag_pairs in window units to match null_vals ordering
    max_lag_w = int(round(MAX_LAG_MIN * WINDOWS_PER_MIN))
    lag_pairs_w = [(l1, l2) for l1 in range(1, max_lag_w) for l2 in range(l1 + 1, max_lag_w + 1)]
    fig, axes = plt.subplots(2, 2, figsize=(12, 10))
    comps = ['redundancy', 'synergy', 'unique_0', 'unique_1']
    titles = ['Redundancy', 'Synergy', 'Unique₁', 'Unique₂']
    cmaps = ['Greens', 'Reds', 'Blues', 'Purples']
    comp_idx = {c: i for i, c in enumerate(comps)}
    min_per_w = MIN_PER_WINDOW
    for ax, comp, title, cmap in zip(axes.flat, comps, titles, cmaps):
        p_mat = np.full((n_lags, n_lags), np.nan); ci = comp_idx[comp]
        for li, (l1w, l2w) in enumerate(lag_pairs_w):
            l1_min = round(l1w * min_per_w, 4)
            l2_min = round(l2w * min_per_w, 4)
            row = global_results[(global_results['lag1_min'] == l1_min) & (global_results['lag2_min'] == l2_min)]
            if row.empty: continue
            observed = row[comp].values[0]; null_dist = null_vals[:, li, ci]
            p = (np.sum(null_dist >= observed) + 1) / (len(null_dist) + 1)
            if l1_min in l_idx and l2_min in l_idx:
                p_mat[l_idx[l1_min], l_idx[l2_min]] = -np.log10(max(p, 1e-10))
        sns.heatmap(p_mat, ax=ax, cmap=cmap, mask=np.isnan(p_mat), xticklabels=tick_labels, yticklabels=tick_labels,
                    cbar_kws={'label': '-log₁₀(p)'})
        for l1i in range(n_lags):
            for l2i in range(n_lags):
                if not np.isnan(p_mat[l1i, l2i]) and p_mat[l1i, l2i] > -np.log10(0.05):
                    ax.text(l2i + 0.5, l1i + 0.5, '*', ha='center', va='center', fontsize=12, fontweight='bold', color='white')
        ax.set_title(title, fontweight='bold'); ax.set_xlabel('Lag 2 (min)'); ax.set_ylabel('Lag 1 (min)')
    plt.suptitle(f'Block-permutation significance ({channel})\n(n={null_vals.shape[0]} perms, * = p < 0.05)',
                 fontsize=14, fontweight='bold')
    plt.tight_layout()
    if save_path:
        plt.savefig(save_path, dpi=150, bbox_inches='tight'); plt.close()


