def add_stage_background(ax, stage_labels):
    for i, stage in enumerate(stage_labels):
        x0 = i * MIN_PER_WINDOW
        x1 = (i + 1) * MIN_PER_WINDOW
        ax.axvspan(x0, x1, alpha=0.15, color=STAGE_COLORS.get(stage, '#D3D3D3'),
                   linewidth=0)


def stage_legend_handles():
    return [Patch(facecolor=STAGE_COLORS[s], alpha=0.5, label=s) for s in STAGE_ORDER]


def common_lag_range(tr):
    present = [s for s in STAGE_ORDER if s in tr['stage'].unique()]
    if len(present) < 2:
        return tr
    sets = []
    for s in present:
        sub = tr[tr['stage'] == s]
        pairs = set(zip(sub['lag1_min'], sub['lag2_min']))
        sets.append(pairs)
    common = sets[0]
    for s in sets[1:]:
        common = common & s
    if len(common) == 0:
        return tr
    common_df = pd.DataFrame(list(common), columns=['lag1_min', 'lag2_min'])
    return tr.merge(common_df, on=['lag1_min', 'lag2_min'], how='inner')


def lag_index(df):
    """Return sorted unique lag values and a value→index mapping."""
    all_lags = sorted(set(df['lag1_min'].unique()) | set(df['lag2_min'].unique()))
    return all_lags, {v: i for i, v in enumerate(all_lags)}


def lag_tick_labels(lag_vals):
    """Compact tick labels: drop trailing zeros for whole numbers."""
    out = []
    for v in lag_vals:
        out.append(f'{v:g}')
    return out


def load_channel_data(ch_short, chash, band_name=None):
    """Load all CSVs/NPZ for one channel (optionally from a band subfolder).
    Returns dict of DataFrames or None if critical data is missing."""
    if band_name:
        ch_dir = RESULTS_DIR / ch_short / band_name
    else:
        ch_dir = RESULTS_DIR / ch_short
    if not ch_dir.exists():
        print(f"  WARNING: no data for {ch_short} at {ch_dir}")
        return None

    label = f"{ch_short}/{band_name}" if band_name else ch_short
    data = {'channel': label, 'ch_dir': ch_dir}

    f = ch_dir / f"global_pid_matrix_{chash}.csv"
    data['global'] = pd.read_csv(f) if f.exists() else None

    f = ch_dir / f"timeresolved_pid_filtered_{chash}.csv"
    data['tr'] = pd.read_csv(f) if f.exists() else None

    f = ch_dir / f"ar1_global_pid_mean_{chash}.csv"
    data['ar1_global'] = pd.read_csv(f) if f.exists() else None

    f = ch_dir / f"ar1_timeresolved_pid_filtered_{chash}.csv"
    data['ar1_tr'] = pd.read_csv(f) if f.exists() else None

    f = ch_dir / f"autocorrelation_{chash}.csv"
    data['autocorr'] = pd.read_csv(f) if f.exists() else None

    f = ch_dir / f"block_perm_null_{chash}.npz"
    if f.exists():
        data['null_vals'] = np.load(f)['null_vals']
    else:
        data['null_vals'] = None

    f = ch_dir / f"stage_labels_{chash}.csv"
    if f.exists():
        sl = pd.read_csv(f)
        data['stage_labels'] = sl['stage'].tolist()
    else:
        data['stage_labels'] = None

    return data


