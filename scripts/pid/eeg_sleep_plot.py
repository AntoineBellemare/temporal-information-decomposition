def plot_cross_electrode_comparison(all_data, save_path=None):
    """Compare PID across electrodes: one boxplot per atom, grouped by channel."""
    channels = [d['channel'] for d in all_data if d['tr'] is not None]
    if len(channels) < 2:
        return

    fig, axes = plt.subplots(1, 4, figsize=(20, 6))
    metrics = ['redundancy', 'synergy', 'unique_total', 'ratio']
    labels = ['Redundancy', 'Synergy', 'Total Unique', 'S/R Ratio']

    # aggregate per channel × stage
    rows = []
    for d in all_data:
        if d['tr'] is None:
            continue
        tr = common_lag_range(d['tr'])
        agg = tr.groupby(['time_min', 'stage']).agg(
            redundancy=('redundancy', 'mean'), synergy=('synergy', 'mean'),
            unique_0=('unique_0', 'mean'), unique_1=('unique_1', 'mean'),
        ).reset_index()
        agg['unique_total'] = agg['unique_0'] + agg['unique_1']
        agg['ratio'] = agg['synergy'] / agg['redundancy'].replace(0, np.nan)
        agg['channel'] = d['channel']
        rows.append(agg)

    combined = pd.concat(rows, ignore_index=True)
    combined = combined[combined['stage'].isin(STAGE_ORDER)]

    for ax, metric, label in zip(axes, metrics, labels):
        sns.boxplot(data=combined, x='stage', y=metric, hue='channel',
                    order=STAGE_ORDER, ax=ax, showfliers=False)
        ax.set_title(label, fontweight='bold')
        ax.set_ylabel(f'{label} (bits)' if metric != 'ratio' else 'S/R')
        ax.set_xlabel('Sleep stage')
        ax.grid(axis='y', alpha=0.3)
        if metric == 'ratio':
            ax.axhline(1.0, color='grey', ls='--', alpha=0.5)
        if ax != axes[0]:
            ax.get_legend().remove()
        else:
            ax.legend(fontsize=7, title='Channel')

    plt.suptitle('Cross-electrode PID comparison by sleep stage',
                 fontsize=14, fontweight='bold')
    plt.tight_layout()
    if save_path:
        plt.savefig(save_path, dpi=150, bbox_inches='tight'); plt.close()


